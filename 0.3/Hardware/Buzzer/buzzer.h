/**
 * @file    buzzer.h
 * @brief   蜂鸣器驱动 (移植自 v1.21/Hardware/lightandbuzzer.h, 简化为只保留 BEEP)
 *
 * ============================================================================
 * 硬件 (来自 empty.syscfg)
 * ============================================================================
 *   BEEP: PA12 (GPIO 输出, 初始低电平)
 *         引脚名: BEEP_A29_PIN / BEEP_A29_IOMUX
 *         注: syscfg 名字 "BEEP_A29" 但实际分配到 PA12 (见
 *             ti_msp_dl_config.c: DL_GPIO_initDigitalOutput(BEEP_A29_IOMUX))
 *
 * ============================================================================
 * 有源蜂鸣器电平逻辑 (与 v1.21 一致)
 * ============================================================================
 *   低电平 → 蜂鸣器响
 *   高电平 → 蜂鸣器静音
 *
 * ============================================================================
 * 使用方法
 * ============================================================================
 *   Buzzer_Init();          // 上电调一次
 *   Buzzer_On();            // 响
 *   Buzzer_Off();           // 静音
 *   Buzzer_Toggle();        // 翻转
 *
 * ============================================================================
 */
#ifndef __BUZZER_H__
#define __BUZZER_H__

#include <stdint.h>

/* 初始化: 设默认静音 (高电平). main() 启动时调一次. */
void Buzzer_Init(void);

/* 控制开关 */
void Buzzer_On(void);
void Buzzer_Off(void);
void Buzzer_Toggle(void);

/* 读当前状态: 1=响, 0=静音 */
uint8_t Buzzer_IsOn(void);

#endif /* __BUZZER_H__ */